import re
import sys
from pathlib import Path

import pytest

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))

import pr_body  # noqa: E402

TEMPLATE = SCRIPTS.parent / ".github" / "pull_request_template.md"


def headings(text):
    return re.findall(r"^## .+$", text, flags=re.MULTILINE)


def test_template_headings_are_all_present_in_the_same_order():
    body = pr_body.build_body(1, "Something.")
    expected = headings(TEMPLATE.read_text(encoding="utf-8"))
    found = [h for h in headings(body) if h in expected]
    assert found == expected


def test_template_gates_and_workload_text_match_the_template():
    template = TEMPLATE.read_text(encoding="utf-8")
    for text in [*pr_body.GATES, *pr_body.WORKLOAD.values()]:
        assert text in template


def test_refs_is_the_default_and_closes_is_optional():
    assert "Refs #7" in pr_body.build_body(7, "x")
    assert "Closes #7" in pr_body.build_body(7, "x", closes=True)
    assert "Closes #7" not in pr_body.build_body(7, "x")


def test_gates_are_unticked_by_default_and_ticked_on_request():
    assert "[x]" not in pr_body.build_body(1, "x")
    body = pr_body.build_body(1, "x", gates_passed=True)
    assert body.count("- [x]") == len(pr_body.GATES)


@pytest.mark.parametrize("key", ["right", "low", "high"])
def test_only_the_chosen_workload_box_is_ticked(key):
    body = pr_body.build_body(1, "x", workload=key)
    ticked = [line for line in body.splitlines() if line.startswith("- [x]")]
    assert ticked == [f"- [x] {pr_body.WORKLOAD[key]}"]


def test_owner_check_section_only_with_no_auto_merge():
    plain = pr_body.build_body(1, "x", owner_checks=["Try it"])
    assert "Owner check" not in plain
    body = pr_body.build_body(1, "x", no_auto_merge=True, owner_checks=["Try it", "Try more"])
    assert "## Owner check before merging" in body
    assert "- [ ] Try it" in body and "- [ ] Try more" in body
    assert "`no-auto-merge`" in body


def test_footer_comes_last_and_nothing_is_added_without_it():
    assert pr_body.build_body(1, "x").rstrip().endswith("-->")
    body = pr_body.build_body(1, "x", footer="Generated by a tool")
    assert body.rstrip().endswith("Generated by a tool")


def test_no_links_are_added_by_the_script():
    assert "http" not in pr_body.build_body(1, "x", gates_passed=True, no_auto_merge=True)


@pytest.mark.parametrize("secret", [
    "github_pat_" + "A" * 30,
    "ghp_" + "b" * 30,
], ids=["fine-grained-style", "classic-style"])
def test_text_that_looks_like_a_token_is_refused(secret):
    for kwargs in ({"summary": secret}, {"summary": "x", "footer": secret},
                   {"summary": "x", "owner_checks": [secret]}):
        with pytest.raises(ValueError):
            pr_body.build_body(1, **kwargs)


@pytest.mark.parametrize("issue", [0, -3])
def test_issue_must_be_positive(issue):
    with pytest.raises(ValueError):
        pr_body.build_body(issue, "x")


def test_unknown_workload_is_refused():
    with pytest.raises(ValueError):
        pr_body.build_body(1, "x", workload="huge")


def test_command_line_prints_the_body(capsys):
    code = pr_body.main(["--issue", "5", "--summary", "Hello", "--gates-passed",
                         "--workload", "right"])
    out = capsys.readouterr().out
    assert code == 0
    assert "Refs #5" in out and "Hello" in out


def test_command_line_refuses_a_token_with_an_error_code(capsys):
    code = pr_body.main(["--issue", "5", "--summary", "github_pat_" + "C" * 30])
    assert code == 2
    assert "token" in capsys.readouterr().err
